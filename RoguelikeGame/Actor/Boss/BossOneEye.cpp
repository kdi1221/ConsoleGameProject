void BossOneEye::Draw()
{
	super::Draw();

	const Vector2Int& centerPos = GetWorldPosition();
	Vector2Int drawPos = centerPos - Vector2Int(40, _countof(testOneEyeAsciiArts) >> 1);

	Renderer& renderer = Renderer::Get();

	for (const std::wstring& oneEyeAsciiLine : testOneEyeAsciiArts)
	{
		renderer.Submit(oneEyeAsciiLine, drawPos, Color::White, static_cast<int>(eRenderSortingOrder::Boss));
		++drawPos.y;
	}
}
